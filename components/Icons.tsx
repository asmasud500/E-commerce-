/** Pick a category icon from the category name; falls back to a generic tag. */
export function categoryIcon(name:string){
  const n=name.toLowerCase();
  const rules:[RegExp,string][]=[
    [/fashion|cloth|shirt|wear|apparel|dress|men|women|kid/,"shirt"],
    [/phone|mobile|tablet|gadget/,"phone"],
    [/laptop|computer|electronic|tech|camera|audio/,"laptop"],
    [/home|kitchen|furniture|living|decor|garden/,"home"],
    [/beauty|health|care|cosmetic|skin|perfume/,"sparkle"],
    [/gift|toy|baby/,"gift"],
    [/book|stationery|office|school/,"book"],
    [/watch|jewel|accessor/,"watch"],
    [/bag|shoe|footwear|travel|luggage/,"bag"],
  ];
  return rules.find(([re])=>re.test(n))?.[1]||"tag";
}
